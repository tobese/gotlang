package transpile

import (
	"fmt"
	"go/scanner"
	"go/token"
)

// RuntimeFuncName is the Göteborg stand-in for a stdin-read helper, in the
// spirit of Python's input(). Go has no such builtin, so unlike the words
// in Keywords this isn't a token swap — it's a real function that gets
// generated and injected into the build when a .got file calls it.
const RuntimeFuncName = "hörru"

// NeedsRuntime reports whether src calls the RuntimeFuncName helper, by
// scanning for it as a bare identifier (so a string literal or comment
// mentioning the word doesn't trigger a false positive).
func NeedsRuntime(src []byte) bool {
	fset := token.NewFileSet()
	file := fset.AddFile("", fset.Base(), len(src))

	var s scanner.Scanner
	s.Init(file, src, nil, 0)
	for {
		_, tok, lit := s.Scan()
		if tok == token.EOF {
			return false
		}
		if tok == token.IDENT && lit == RuntimeFuncName {
			return true
		}
	}
}

// RuntimeSource returns the Go source defining the hörru() helper, declared
// under packageName so it drops straight into the build dir alongside the
// translated files it's needed by.
func RuntimeSource(packageName string) []byte {
	return []byte(fmt.Sprintf(`// Code generated by gotlang; the %[1]s() helper has no Go
// equivalent, so it's injected here rather than produced by token swapping.
package %[2]s

import (
	"bufio"
	"os"
)

var gotlangStdin = bufio.NewScanner(os.Stdin)

func %[1]s() string {
	gotlangStdin.Scan()
	return gotlangStdin.Text()
}
`, RuntimeFuncName, packageName))
}
