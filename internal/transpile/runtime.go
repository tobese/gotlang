package transpile

import (
	"fmt"
	"go/scanner"
	"go/token"
	"strings"
)

// InputFuncName is the Göteborg stand-in for a stdin-read helper, in the
// spirit of Python's input(). Go has no such builtin, so unlike the words
// in Keywords this isn't a token swap — it's a real function that gets
// generated and injected into the build when a .got file calls it.
const InputFuncName = "hörru"

// PrintFuncName is the Göteborg stand-in for a println helper. "Tjöta"
// means to yap, to go on and on — fitting for a function that writes to
// stdout. It's capitalized to keep it distinct from the "tjöta" keyword
// (which stands for "for"); keyword swapping only ever matches the exact,
// lowercase spelling in Keywords, so the two never collide.
const PrintFuncName = "Tjöta"

// RuntimeUsage reports which runtime helpers (words with no Go equivalent,
// generated into gotlang_runtime.go rather than produced by token
// swapping) a .got source file calls.
type RuntimeUsage struct {
	Input bool
	Print bool
}

// Any reports whether any runtime helper is used, i.e. whether a runtime
// file needs to be generated at all.
func (u RuntimeUsage) Any() bool {
	return u.Input || u.Print
}

// Merge ORs another usage into u.
func (u *RuntimeUsage) Merge(other RuntimeUsage) {
	u.Input = u.Input || other.Input
	u.Print = u.Print || other.Print
}

// NeedsRuntime reports which runtime helpers src calls, by scanning for
// them as bare identifiers (so a string literal or comment mentioning the
// word doesn't trigger a false positive).
func NeedsRuntime(src []byte) RuntimeUsage {
	fset := token.NewFileSet()
	file := fset.AddFile("", fset.Base(), len(src))

	var s scanner.Scanner
	s.Init(file, src, nil, 0)
	var usage RuntimeUsage
	for {
		_, tok, lit := s.Scan()
		if tok == token.EOF {
			return usage
		}
		if tok != token.IDENT {
			continue
		}
		switch lit {
		case InputFuncName:
			usage.Input = true
		case PrintFuncName:
			usage.Print = true
		}
	}
}

// RuntimeSource returns the Go source defining whichever runtime helpers
// usage calls for, declared under packageName so it drops straight into
// the build dir alongside the translated files it's needed by.
func RuntimeSource(packageName string, usage RuntimeUsage) []byte {
	var imports []string
	var body strings.Builder

	if usage.Input {
		imports = append(imports, `"bufio"`, `"os"`)
		fmt.Fprintf(&body, `
var gotlangStdin = bufio.NewScanner(os.Stdin)

func %s() string {
	gotlangStdin.Scan()
	return gotlangStdin.Text()
}
`, InputFuncName)
	}
	if usage.Print {
		imports = append(imports, `"fmt"`)
		fmt.Fprintf(&body, `
func %s(a ...any) {
	fmt.Println(a...)
}
`, PrintFuncName)
	}

	var importBlock string
	if len(imports) > 0 {
		importBlock = "\nimport (\n\t" + strings.Join(imports, "\n\t") + "\n)\n"
	}

	return []byte(fmt.Sprintf(`// Code generated by gotlang; the runtime helper(s) below have no Go
// equivalent, so they're injected here rather than produced by token
// swapping.
package %s
%s%s`, packageName, importBlock, body.String()))
}
